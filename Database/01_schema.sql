-- PostgreSQL 15+. Ejecución atómica y solo sobre una base sin tablas de usuario.
BEGIN;
SELECT pg_advisory_xact_lock(81370608);
DO $$
BEGIN
    IF current_database() <> 'dashboard_caja_ahorro' OR current_user <> 'dashboard_user' THEN
        RAISE EXCEPTION 'Destino no autorizado';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind IN ('r', 'p', 'f')
          AND n.nspname NOT IN ('pg_catalog', 'information_schema')
          AND n.nspname NOT LIKE 'pg_toast%'
          AND n.nspname NOT LIKE 'pg_temp_%'
    ) THEN
        RAISE EXCEPTION 'La base contiene tablas; se cancela la creación';
    END IF;
END $$;
SET LOCAL search_path = public, pg_catalog;

CREATE TABLE archivo_fuente (
    archivo_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fuente text NOT NULL CHECK (fuente IN ('CNBV', 'FONACOT', 'SNIIV')),
    ruta text NOT NULL,
    url text,
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-fA-F]{64}$'),
    tamano_bytes bigint NOT NULL CHECK (tamano_bytes >= 0),
    descargado_en timestamptz,
    periodo_desde date,
    periodo_hasta date,
    rol text NOT NULL CHECK (rol IN ('hechos', 'diccionario', 'validacion')),
    CONSTRAINT archivo_periodo_ck CHECK (periodo_desde IS NULL OR periodo_hasta IS NULL OR periodo_desde <= periodo_hasta),
    CONSTRAINT archivo_ruta_hash_uq UNIQUE (ruta, sha256)
);

CREATE TABLE ejecucion_etl (
    ejecucion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iniciada_en timestamptz NOT NULL,
    terminada_en timestamptz,
    estado text NOT NULL CHECK (estado IN ('iniciada', 'exitosa', 'fallida')),
    version_proceso text NOT NULL,
    observaciones text,
    CONSTRAINT ejecucion_fechas_ck CHECK (terminada_en IS NULL OR terminada_en >= iniciada_en)
);

CREATE TABLE ejecucion_archivo (
    ejecucion_id bigint NOT NULL REFERENCES ejecucion_etl (ejecucion_id),
    archivo_id bigint NOT NULL REFERENCES archivo_fuente (archivo_id),
    funcion text NOT NULL CHECK (funcion IN ('hechos', 'metadato', 'contraste')),
    hash_verificado boolean NOT NULL,
    PRIMARY KEY (ejecucion_id, archivo_id)
);

CREATE TABLE dim_mes (
    mes_id date PRIMARY KEY CHECK (EXTRACT(DAY FROM mes_id) = 1)
);

CREATE TABLE dim_institucion (
    institucion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_seis char(6) NOT NULL UNIQUE CHECK (clave_seis ~ '^[0-9]{6}$'),
    clave_boletin text NOT NULL,
    clave_catalogo text,
    nombre text NOT NULL
);

CREATE TABLE dim_concepto_cnbv (
    concepto_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archivo_id bigint NOT NULL REFERENCES archivo_fuente (archivo_id),
    hoja text NOT NULL CHECK (hoja = 'Series'),
    fila_series integer NOT NULL CHECK (fila_series > 0),
    codigo_original text,
    nombre text NOT NULL,
    naturaleza text NOT NULL CHECK (naturaleza IN ('saldo', 'flujo_mensual', 'acumulado_ejercicio', 'flujo_12m', 'conteo', 'porcentaje')),
    unidad_origen text NOT NULL CHECK (unidad_origen IN ('millones_mxn_inferidos', 'conteo', 'porcentaje')),
    unidad_normalizada text NOT NULL CHECK (unidad_normalizada IN ('mxn', 'conteo', 'porcentaje')),
    CONSTRAINT concepto_unidad_ck CHECK (
        (naturaleza IN ('saldo', 'flujo_mensual', 'acumulado_ejercicio', 'flujo_12m') AND unidad_origen = 'millones_mxn_inferidos' AND unidad_normalizada = 'mxn') OR
        (naturaleza = 'conteo' AND unidad_origen = 'conteo' AND unidad_normalizada = 'conteo') OR
        (naturaleza = 'porcentaje' AND unidad_origen = 'porcentaje' AND unidad_normalizada = 'porcentaje')
    ),
    CONSTRAINT concepto_fila_uq UNIQUE (archivo_id, hoja, fila_series),
    CONSTRAINT concepto_archivo_uq UNIQUE (concepto_id, archivo_id)
);

CREATE TABLE dim_ambito_fonacot (
    ambito_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo text NOT NULL CHECK (tipo IN ('entidad', 'canal')),
    nombre_canonico text NOT NULL,
    CONSTRAINT ambito_nombre_uq UNIQUE (tipo, nombre_canonico),
    CONSTRAINT ambito_app_ck CHECK (upper(nombre_canonico) <> 'APP MOVIL' OR tipo = 'canal')
);

CREATE TABLE dim_genero_fonacot (
    genero_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etiqueta text NOT NULL UNIQUE CHECK (etiqueta IN ('mujeres', 'hombres'))
);

CREATE TABLE hecho_cnbv_sector_mes (
    sector_mes_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id bigint NOT NULL,
    archivo_id bigint NOT NULL,
    mes_id date NOT NULL REFERENCES dim_mes (mes_id),
    concepto_id bigint NOT NULL,
    valor numeric(30,6),
    CONSTRAINT sector_ejecucion_archivo_fk FOREIGN KEY (ejecucion_id, archivo_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT sector_concepto_archivo_fk FOREIGN KEY (concepto_id, archivo_id) REFERENCES dim_concepto_cnbv (concepto_id, archivo_id),
    CONSTRAINT sector_grano_uq UNIQUE (ejecucion_id, mes_id, concepto_id)
);

CREATE TABLE hecho_cnbv_institucion_trim (
    institucion_trim_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id bigint NOT NULL,
    archivo_id bigint NOT NULL,
    mes_id date NOT NULL REFERENCES dim_mes (mes_id) CHECK (EXTRACT(MONTH FROM mes_id) IN (3, 6, 9, 12)),
    institucion_id bigint NOT NULL REFERENCES dim_institucion (institucion_id),
    estado_reporte text NOT NULL CHECK (estado_reporte IN ('publicado', 'parcial', 'no_reportado')),
    socios bigint,
    sucursales bigint,
    activo_mxn numeric(30,6),
    disponibilidades_mxn numeric(30,6),
    cartera_vigente_mxn numeric(30,6),
    cartera_vencida_mxn numeric(30,6),
    estimacion_mxn numeric(30,6),
    captacion_total_mxn numeric(30,6),
    captacion_tradicional_mxn numeric(30,6),
    ingresos_intereses_trim_mxn numeric(30,6),
    gastos_intereses_trim_mxn numeric(30,6),
    imor_pct numeric(20,10),
    nicap_pct numeric(20,10),
    participacion_activo_pct numeric(20,10),
    categoria_nicap text,
    tasa_activa_pct numeric(20,10),
    tasa_pasiva_total_pct numeric(20,10),
    tasa_pasiva_tradicional_pct numeric(20,10),
    CONSTRAINT institucion_ejecucion_archivo_fk FOREIGN KEY (ejecucion_id, archivo_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT institucion_grano_uq UNIQUE (ejecucion_id, mes_id, institucion_id)
);

CREATE TABLE hecho_cnbv_total_trim (
    total_trim_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id bigint NOT NULL,
    archivo_id bigint NOT NULL,
    mes_id date NOT NULL REFERENCES dim_mes (mes_id) CHECK (EXTRACT(MONTH FROM mes_id) IN (3, 6, 9, 12)),
    activo_mxn numeric(30,6),
    cartera_vigente_mxn numeric(30,6),
    captacion_total_mxn numeric(30,6),
    imor_pct numeric(20,10),
    icor_pct numeric(20,10),
    nicap_pct numeric(20,10),
    roa_pct numeric(20,10),
    CONSTRAINT total_ejecucion_archivo_fk FOREIGN KEY (ejecucion_id, archivo_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT total_grano_uq UNIQUE (ejecucion_id, mes_id)
);

CREATE TABLE hecho_fonacot_mes (
    fonacot_mes_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id bigint NOT NULL REFERENCES ejecucion_etl (ejecucion_id),
    archivo_creditos_id bigint,
    archivo_monto_id bigint,
    mes_id date NOT NULL REFERENCES dim_mes (mes_id),
    ambito_id bigint NOT NULL REFERENCES dim_ambito_fonacot (ambito_id),
    genero_id bigint NOT NULL REFERENCES dim_genero_fonacot (genero_id),
    etiqueta_creditos_original text,
    etiqueta_monto_original text,
    creditos bigint,
    monto_mxn numeric(30,6),
    CONSTRAINT fonacot_creditos_archivo_fk FOREIGN KEY (ejecucion_id, archivo_creditos_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT fonacot_monto_archivo_fk FOREIGN KEY (ejecucion_id, archivo_monto_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT fonacot_fuentes_ck CHECK (archivo_creditos_id IS NOT NULL OR archivo_monto_id IS NOT NULL),
    CONSTRAINT fonacot_creditos_ck CHECK ((archivo_creditos_id IS NULL AND etiqueta_creditos_original IS NULL AND creditos IS NULL) OR (archivo_creditos_id IS NOT NULL AND etiqueta_creditos_original IS NOT NULL)),
    CONSTRAINT fonacot_monto_ck CHECK ((archivo_monto_id IS NULL AND etiqueta_monto_original IS NULL AND monto_mxn IS NULL) OR (archivo_monto_id IS NOT NULL AND etiqueta_monto_original IS NOT NULL)),
    CONSTRAINT fonacot_grano_uq UNIQUE (ejecucion_id, mes_id, ambito_id, genero_id)
);

CREATE TABLE hecho_sniiv_mes (
    sniiv_mes_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_id bigint NOT NULL,
    archivo_id bigint NOT NULL,
    mes_id date NOT NULL REFERENCES dim_mes (mes_id),
    cve_ent text,
    cve_mun text,
    entidad text,
    municipio text,
    organismo text,
    modalidad text,
    destino text,
    tipo text,
    sexo text,
    edad_rango text,
    ingresos_rango text,
    vivienda_valor text,
    acciones bigint,
    monto_mxn numeric(30,6),
    CONSTRAINT sniiv_ejecucion_archivo_fk FOREIGN KEY (ejecucion_id, archivo_id) REFERENCES ejecucion_archivo (ejecucion_id, archivo_id),
    CONSTRAINT sniiv_grano_uq UNIQUE NULLS NOT DISTINCT (ejecucion_id, mes_id, cve_ent, cve_mun, organismo, modalidad, destino, tipo, sexo, edad_rango, ingresos_rango, vivienda_valor)
);

-- Índices adicionales: PK y UNIQUE ya generan sus propios índices.
CREATE INDEX ejecucion_archivo_archivo_idx ON ejecucion_archivo (archivo_id);
CREATE INDEX sector_concepto_archivo_idx ON hecho_cnbv_sector_mes (concepto_id, archivo_id);
CREATE INDEX sector_archivo_idx ON hecho_cnbv_sector_mes (ejecucion_id, archivo_id);
CREATE INDEX institucion_archivo_idx ON hecho_cnbv_institucion_trim (ejecucion_id, archivo_id);
CREATE INDEX institucion_institucion_mes_idx ON hecho_cnbv_institucion_trim (institucion_id, mes_id);
CREATE INDEX total_archivo_idx ON hecho_cnbv_total_trim (ejecucion_id, archivo_id);
CREATE INDEX fonacot_creditos_archivo_idx ON hecho_fonacot_mes (ejecucion_id, archivo_creditos_id);
CREATE INDEX fonacot_monto_archivo_idx ON hecho_fonacot_mes (ejecucion_id, archivo_monto_id);
CREATE INDEX fonacot_ambito_genero_mes_idx ON hecho_fonacot_mes (ambito_id, genero_id, mes_id);
CREATE INDEX sniiv_archivo_idx ON hecho_sniiv_mes (ejecucion_id, archivo_id);
CREATE INDEX sniiv_mes_entidad_organismo_sexo_idx ON hecho_sniiv_mes (mes_id, cve_ent, organismo, sexo);
COMMIT;
